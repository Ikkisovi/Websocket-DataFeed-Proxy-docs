import assert from 'node:assert/strict';
import { encode } from '@msgpack/msgpack';
import { MarketStream, loadHistory, normalizeBars, mergeBars, movingAverage, decodeFrames } from '../public/chart/chart-data.mjs';

const row = (minute, close = 101) => ({ t: `2026-10-01T14:${String(minute).padStart(2, '0')}:00Z`, o: 100, h: 110, l: 90, c: close, v: 100 });
const data = normalizeBars([row(2), row(1), row(2, 102), { ...row(3), c: null }, { ...row(4), h: 95 }]);
assert.equal(data.length, 2);
assert.equal(data[1].close, 102);
assert.equal(mergeBars(data, normalizeBars([row(2, 103), row(3)]))[1].close, 103);
assert.deepEqual(movingAverage(data, 2), [{ time: data[1].time, value: 101.5 }]);
const trade = { T: 't', S: 'NVDA', p: 101, t: row(1).t };
assert.deepEqual(await decodeFrames(JSON.stringify([trade])), [trade]);
assert.deepEqual(await decodeFrames(encode([trade])), [trade]);
assert.deepEqual(await decodeFrames(encode([trade]).slice().buffer), [trade]);
assert.deepEqual(await decodeFrames(new Blob([encode([trade])])), [trade]);
let calls = 0;
const history = await loadHistory({ asset: 'stock', symbol: 'NVDA', timeframe: '1m', start: Date.parse(row(0).t), end: Date.parse(row(5).t), token: 'synthetic-only', fetcher: async (url, options) => {
  assert.equal(options.headers.Authorization, 'Bearer synthetic-only');
  const params = new URL(`http://local${url}`).searchParams;
  assert.equal(params.get('timeframe'), '1Min');
  calls++;
  if (calls === 1) return Response.json({ bars: [row(3), row(2)], next_page_token: 'next' });
  assert.equal(params.get('page_token'), 'next');
  return Response.json({ bars: [row(1), row(2, 105)], next_page_token: null });
} });
assert.equal(history.bars.length, 3);
assert.equal(history.bars[1].close, 105);
assert.equal(history.truncated, false);
const params = { asset: 'stock', symbol: 'NVDA', timeframe: '1m', start: Date.parse(row(0).t), end: Date.parse(row(5).t), token: 'synthetic-only' };
const partial = await loadHistory({ ...params, maxPages: 1, fetcher: async () => Response.json({ bars: [row(1)], next_page_token: 'next' }) });
assert.equal(partial.truncated, true);
await assert.rejects(loadHistory({ ...params, fetcher: async () => new Response('', { status: 403 }) }), error => error.status === 403);
await assert.rejects(loadHistory({ ...params, fetcher: async () => Response.json({ bars: [{ ...row(1), c: null }] }) }), /无效/);
await assert.rejects(loadHistory({ ...params, fetcher: async () => Response.json({ bars: [row(1)], next_page_token: 'loop' }) }), /分页/);
let socket, frames = [], states = [];
const market = new MarketStream({ asset: 'stock', symbols: ['NVDA'], token: 'synthetic-only', onStatus: state => states.push(state), onFrame: frame => frames.push(frame), socketFactory: url => {
  assert.equal(url, 'wss://leandata.uk/stream');
  socket = { readyState: 1, sent: [], send(data) { this.sent.push(JSON.parse(data)); }, close() { this.readyState = 3; this.onclose?.(); } };
  return socket;
} });
socket.onopen();
assert.deepEqual(socket.sent[0], { action: 'auth', token: 'synthetic-only' });
socket.onmessage({ data: JSON.stringify({ T: 'success', msg: 'authenticated' }) });
await new Promise(resolve => setImmediate(resolve));
assert.deepEqual(socket.sent[1], { action: 'subscribe', trades: ['NVDA'], quotes: ['NVDA'] });
socket.onmessage({ data: JSON.stringify({ T: 'subscription', subjects: ['market.alpaca.stock.trades.NVDA'] }) });
socket.onmessage({ data: encode([trade, { ...trade, S: 'OTHER' }]).slice().buffer });
await new Promise(resolve => setImmediate(resolve));
assert.equal(states.at(-1), 'connected');
assert.deepEqual(frames, [trade]);
socket.onmessage({ data: JSON.stringify({ T: 'error', code: 401 }) });
await new Promise(resolve => setImmediate(resolve));
assert.equal(market.stopped, true);
assert.equal(market.token, '');
assert.equal(states.at(-1), 'error');
console.log('Chart data: normalization, revisions, binary/JSON decoding, paging, permission failures and WS lifecycle passed.');
